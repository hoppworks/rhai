#!/usr/bin/env bash
set -euo pipefail
ATTEMPT="/var/roothome/rhai-evidence/linux-managed-spawn-lifecycle-20261009T1850Z/attempt01"
SESSION_SCOPE="/root/.local/share/agent-builds/rhai/managed-spawn-lifecycle-20261009T1850Z-01"
RUNNER="/var/home/workhorse/projects/agent-skills/tools/run_scoped.py"
test ! -e "$ATTEMPT"
mkdir -p "$(dirname "$ATTEMPT")"; mkdir "$ATTEMPT"; chmod 700 "$ATTEMPT"
cp "$(dirname "$0")/payload.sh" "$ATTEMPT/payload.sh"
cp "$(dirname "$0")/inputs.json" "$ATTEMPT/inputs.json"
chmod 600 "$ATTEMPT/inputs.json"; chmod 700 "$ATTEMPT/payload.sh"
test ! -e "$SESSION_SCOPE"
test "$(sha256sum "$RUNNER" | cut -d' ' -f1)" = "25d42cec15827652d08148f51d7f226aa23bbb58ee96ffd68594548044428c2e"
printf 'utc=' > "$ATTEMPT/preflight.txt"; date -u '+%Y-%m-%dT%H:%M:%SZ' >> "$ATTEMPT/preflight.txt"
uname -a >> "$ATTEMPT/preflight.txt"
printf 'load=' >> "$ATTEMPT/preflight.txt"; cat /proc/loadavg >> "$ATTEMPT/preflight.txt"
awk '/MemAvailable/ {print "mem_available_kib=" $2}' /proc/meminfo >> "$ATTEMPT/preflight.txt"
df -B1 /root/.local/share/agent-builds/rhai >> "$ATTEMPT/preflight.txt"
printf 'cargo_processes=' >> "$ATTEMPT/preflight.txt"; ps -eo comm | awk '$1=="cargo" {n++} END {print n+0}' >> "$ATTEMPT/preflight.txt"
printf 'rustc_processes=' >> "$ATTEMPT/preflight.txt"; ps -eo comm | awk '$1=="rustc" {n++} END {print n+0}' >> "$ATTEMPT/preflight.txt"
stat -c '%d %i %u %g %a' /root/.local/share/agent-builds/rhai > "$ATTEMPT/scope-parent.identity"
mkdir -m 700 "$SESSION_SCOPE"; stat -c '%d %i %u %g %a' "$SESSION_SCOPE" > "$ATTEMPT/session-scope.identity"
printf '%s\n' "$SESSION_SCOPE" > "$ATTEMPT/session-scope.path"
printf '%s\n' 'runner=/var/home/workhorse/projects/agent-skills/tools/run_scoped.py' 'timeout_seconds=600' 'argv=python3 run_scoped.py --timeout 600 -- bash payload.sh' 'CARGO_BUILD_JOBS=2' > "$ATTEMPT/runner-command.txt"
cd "$ATTEMPT"; SECONDS=0; set +e
TMPDIR="$SESSION_SCOPE" /usr/bin/python3 "$RUNNER" --timeout 600 -- bash "$ATTEMPT/payload.sh" > "$ATTEMPT/runner.stdout" 2> "$ATTEMPT/runner.stderr"
status=$?; set -e
printf '%s\n' "$status" > "$ATTEMPT/runner.status"; printf '%s\n' "$SECONDS" > "$ATTEMPT/runner.elapsed-seconds"
stat -c '%d %i %u %g %a' "$SESSION_SCOPE" > "$ATTEMPT/session-scope.identity.after-run"
remaining="$(find "$SESSION_SCOPE" -mindepth 1 -maxdepth 1 -print -quit)"
if [ -z "$remaining" ]; then rmdir "$SESSION_SCOPE"; printf 'retired_exact_empty_scope=true\n' > "$ATTEMPT/cleanup.txt"; else printf 'retired_exact_empty_scope=false\nremaining=%s\n' "$remaining" > "$ATTEMPT/cleanup.txt"; fi
printf 'runner_status=%s\nelapsed_seconds=%s\n' "$status" "$SECONDS" > "$ATTEMPT/outer-result.txt"
exit "$status"
